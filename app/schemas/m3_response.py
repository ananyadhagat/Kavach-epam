"""Agent 3 response contract for the M3 duplicate-detection endpoint.

This is the wire contract in ``b92.md``. It is intentionally separate from the
internal Phase 2 :class:`~app.schemas.duplicate_response.DuplicateDetectionResponse`
and from the decision policy's domain objects: the HTTP mapper is the only place
that adapts an internal outcome to this shape.

Deliberate contract notes
-------------------------
* Every one of the 11 top-level fields is always emitted. Optional *values* are
  ``null``; they are never omitted.
* Candidate ``signals`` is not implemented because the internal ranked candidate
  does not carry per-candidate signal details. The Agent 3 contract makes it
  optional, so omitting the key is valid.
* Agent 3 describes identifiers as UUID strings. The upstream Agent 1 payload
  uses opaque incident ids (for example ``INC-2026-001``), and the internal
  ``Complaint`` model treats ids as opaque 1-64 character strings. This schema
  therefore validates non-empty strings rather than UUID format. ``check_id`` is
  generated by M3 as a real UUID, so that half of the contract is honoured.
* ``score`` and ``similarity_score`` are similarity/ranking values in ``[0, 1]``
  and are never confidence values.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Annotated

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    StringConstraints,
    field_serializer,
    field_validator,
    model_validator,
)

from app.schemas.duplicate_response import Decision

#: UPPER_SNAKE machine-readable reason/error code.
Code = Annotated[str, StringConstraints(pattern=r"^[A-Z0-9_]+$")]


class ProcessingStatus(str, Enum):
    """Whether the candidate search behind a response was complete."""

    COMPLETED = "COMPLETED"
    PARTIAL = "PARTIAL"
    FAILED = "FAILED"


class M3Error(BaseModel):
    """A machine-readable explanation for an incomplete or failed check."""

    model_config = ConfigDict(extra="forbid")

    code: Code = Field(description="UPPER_SNAKE error code.")
    message: str = Field(description="Human-readable error message.")


class M3Candidate(BaseModel):
    """One retrieved and scored candidate.

    ``signals`` is deliberately omitted: it is optional in the Agent 3 contract
    and the internal ranked candidate does not carry it.
    """

    model_config = ConfigDict(extra="forbid")

    matched_incident_id: str = Field(min_length=1, max_length=64)
    similarity_score: float = Field(ge=0.0, le=1.0, allow_inf_nan=False)
    reason_codes: list[Code] = Field(default_factory=list)


class M3DuplicateCheckResponse(BaseModel):
    """The exact Agent 3 response shape for one duplicate check.

    Cross-field invariants (mirroring ``b92.md``):

    * ``error`` is present exactly when processing is ``PARTIAL`` or ``FAILED``.
    * ``PARTIAL`` and ``FAILED`` always force ``REVIEW_REQUIRED``.
    * ``NEW`` has a null ``matched_incident_id`` and null ``score``.
    * For any other decision, the top-level match and score repeat the first
      candidate when one exists, and are both null when none exists.
    * Candidates are ordered by descending ``similarity_score``.
    """

    model_config = ConfigDict(extra="forbid")

    check_id: str = Field(min_length=1)
    incident_id: str = Field(min_length=1, max_length=64)
    decision: Decision
    processing_status: ProcessingStatus
    policy_version: str = Field(min_length=1)
    checked_at: datetime
    matched_incident_id: str | None = Field(default=None, max_length=64)
    score: float | None = Field(default=None, ge=0.0, le=1.0, allow_inf_nan=False)
    reason_codes: list[Code] = Field(default_factory=list)
    candidates: list[M3Candidate] = Field(default_factory=list)
    error: M3Error | None = None

    @field_validator("checked_at")
    @classmethod
    def _require_aware_utc(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("checked_at must be timezone-aware")
        return value.astimezone(timezone.utc)

    @field_serializer("checked_at")
    def _serialize_checked_at(self, value: datetime) -> str:
        """Emit UTC ISO 8601 with a trailing ``Z`` (Agent 3 contract)."""
        return value.astimezone(timezone.utc).isoformat().replace("+00:00", "Z")

    @model_validator(mode="after")
    def _validate_contract_invariants(self) -> "M3DuplicateCheckResponse":
        incomplete = self.processing_status is not ProcessingStatus.COMPLETED

        if incomplete and self.error is None:
            raise ValueError(
                "a PARTIAL or FAILED response must include an error object"
            )
        if not incomplete and self.error is not None:
            raise ValueError("a COMPLETED response must have a null error")

        if incomplete and self.decision is not Decision.REVIEW_REQUIRED:
            raise ValueError(
                "a PARTIAL or FAILED response must use REVIEW_REQUIRED"
            )

        if self.decision is Decision.NEW:
            if self.matched_incident_id is not None or self.score is not None:
                raise ValueError(
                    "a NEW response must have null matched_incident_id and score"
                )
        elif self.candidates:
            leading = self.candidates[0]
            if (
                self.matched_incident_id != leading.matched_incident_id
                or self.score != leading.similarity_score
            ):
                raise ValueError(
                    "matched_incident_id and score must repeat the first "
                    "candidate for a non-NEW response"
                )
        elif self.matched_incident_id is not None or self.score is not None:
            raise ValueError(
                "a response without candidates must have null "
                "matched_incident_id and score"
            )

        if self.decision is Decision.DUPLICATE:
            if incomplete:
                raise ValueError("DUPLICATE requires COMPLETED processing")
            if not self.candidates:
                raise ValueError("DUPLICATE requires at least one candidate")

        scores = [candidate.similarity_score for candidate in self.candidates]
        if any(
            higher < lower
            for higher, lower in zip(scores, scores[1:], strict=False)
        ):
            raise ValueError(
                "candidates must be ordered by descending similarity_score"
            )

        return self


