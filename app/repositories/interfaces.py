"""Repository contracts so verification policy is independent of storage choice."""

from typing import Protocol


class TaskRepositoryInterface(Protocol):
    def get(self, task_id: str) -> dict | None: ...
    def save(self, task_id: str, task: dict) -> None: ...
    def save_sanitation_plan(self, task_id: str, plan: dict, authoritative_site: dict | None = None) -> None: ...


class EvidenceRepositoryInterface(Protocol):
    def get(self, submission_id: str) -> dict | None: ...
    def load_image(self, evidence_item: dict) -> tuple[bytes, str]: ...
    def get_evidence_records(self, evidence_ids: list[str]) -> list[dict]: ...
    def get_location_events(self, event_ids: list[str]) -> list[dict]: ...
    def save_evidence_record(self, evidence_record: dict) -> None: ...
    def save_location_event(self, location_event: dict) -> None: ...


class VerificationRepositoryInterface(Protocol):
    def get_existing(self, task_id: str, submission_id: str, rule_version: str) -> dict | None: ...
    def get_or_create(self, task_id: str, submission_id: str, rule_version: str, create_response) -> dict: ...
    def save(self, response: dict) -> None: ...
